/**
 * 橱窗数据 —— 整个小程序的内容都在这个文件里
 *
 * 换内容只需要改这里，三个页面（首页 / 详情 / 关于）都不用动。
 * 想改成商品、课程、作品、活动、菜单……都是同一套结构。
 */

export interface ShowcaseSection {
  /** 模块名，显示在卡片标题位置 */
  title: string
  /** 一句话说明，控制在 20 字以内最整齐 */
  desc: string
}

export interface ShowcaseItem {
  /** 唯一标识。详情页靠它取数据，改完记得别和别的条目重复 */
  id: string
  /** 卡片主标题 */
  title: string
  /** 标题下面那行小字 */
  subtitle: string
  /** 所属分类，值要和文件底部 categories 里的某一项完全一致 */
  category: string
  /** 图标里显示的 1-2 个字 */
  badge: string
  /** 图标渐变起点色 */
  from: string
  /** 图标渐变终点色 */
  to: string
  /** 卡片上的小标签，建议 2-3 个，多了会挤 */
  tags: string[]
  /** 详情页开头的介绍段落 */
  summary: string
  /** 核心亮点，建议 3-4 条，每条一句话说清一个价值 */
  highlights: string[]
  /** 内容模块，建议正好 4 个，双列排版刚好铺满两行 */
  sections: ShowcaseSection[]
  /** 适用场景，建议 3-4 个短词 */
  usages: string[]
  /** 详情信息，左标签右内容，建议 3-4 行 */
  details: { label: string; value: string }[]
}

